#!/usr/bin/env python3
"""Check the committed reference pages against the binary's command and schema constants.

This is the acceptance check for the reference docs: the CLI page must cover exactly the
`V0_1_COMMANDS` and `V0_2_COMMANDS` constants (the same set `help_lists_every_v0_1_command`
asserts), and every type exported by `vowp_protocol::schema::all_schemas` must have a parseable
schema page.

It reads repository files only, so it runs without a built binary. Use
`python3 docs/reference/generate.py --check` to also compare the pages with fresh output.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "docs" / "reference"
CLI_PAGE = REFERENCE / "cli.md"
SCHEMA_DIR = REFERENCE / "schema"
CLI_RS = ROOT / "crates" / "vowp-cli" / "src" / "cli.rs"
SCHEMA_RS = ROOT / "crates" / "vowp-protocol" / "src" / "schema.rs"

GENERATED = "<!-- generated by docs/reference/generate.py; do not edit -->"


def fail(message: str) -> None:
    print(f"FAIL  reference: {message}", file=sys.stderr)


def command_const(name: str) -> list[str]:
    text = CLI_RS.read_text(encoding="utf-8")
    match = re.search(rf"pub const {name}:.*?=\s*&\[(.*?)\];", text, re.DOTALL)
    if not match:
        raise SystemExit(f"cannot parse {name} from {CLI_RS}")
    return re.findall(r'"([^"]+)"', match.group(1))


def top_level_commands() -> list[str]:
    commands = command_const("V0_1_COMMANDS") + command_const("V0_2_COMMANDS")
    return list(dict.fromkeys(commands))


def schema_names() -> list[str]:
    text = SCHEMA_RS.read_text(encoding="utf-8")
    names = re.findall(r'schemas\.insert\("([A-Za-z0-9_]+)"', text)
    if not names:
        raise SystemExit(f"cannot parse exported schema names from {SCHEMA_RS}")
    return names


def slugify_type(name: str) -> str:
    first = re.sub(r"(?<!^)(?=[A-Z])", "-", name)
    return first.lower()


def cli_sections(text: str) -> list[tuple[list[str], int]]:
    sections = []
    for number, line in enumerate(text.splitlines(), 1):
        match = re.match(r"^#{2,6}\s+`vowp(?: ([^`]+))?`\s*$", line)
        if match:
            path = match.group(1).split() if match.group(1) else []
            sections.append((path, number))
    return sections


def check_cli() -> list[str]:
    failures = []
    expected = top_level_commands()
    if not CLI_PAGE.is_file():
        return [f"missing page: {CLI_PAGE.relative_to(ROOT)}"]
    text = CLI_PAGE.read_text(encoding="utf-8")
    if GENERATED not in text:
        failures.append("cli.md is missing the generated-page marker")
    sections = cli_sections(text)
    if not sections or sections[0][0]:
        failures.append("cli.md does not start with the `vowp` root help section")
    documented = [path[0] for path, _ in sections if len(path) == 1]
    duplicates = sorted({name for name in documented if documented.count(name) > 1})
    if duplicates:
        failures.append("duplicate top-level command sections: " + ", ".join(duplicates))
    missing = [name for name in expected if name not in documented]
    extra = [name for name in documented if name not in expected]
    if missing:
        failures.append("commands in V0_1_COMMANDS/V0_2_COMMANDS but not in cli.md: " + ", ".join(missing))
    if extra:
        failures.append("commands in cli.md but not in V0_1_COMMANDS/V0_2_COMMANDS: " + ", ".join(extra))
    for path, number in sections:
        if path and path[0] not in expected:
            failures.append(f"cli.md:{number}: `vowp {' '.join(path)}` is not in V0_1_COMMANDS/V0_2_COMMANDS")
    if "__window" in expected and "__window" not in documented:
        failures.append("the hidden __window command is missing from cli.md")
    return failures


def check_schema() -> list[str]:
    failures = []
    index = SCHEMA_DIR / "README.md"
    if not index.is_file():
        return [f"missing page: {index.relative_to(ROOT)}"]
    index_text = index.read_text(encoding="utf-8")
    if GENERATED not in index_text:
        failures.append("schema/README.md is missing the generated-page marker")
    expected = schema_names()
    for name in expected:
        slug = slugify_type(name)
        link = f"]({slug}.md)"
        if link not in index_text:
            failures.append(f"schema/README.md does not link {name} ({slug}.md)")
        page = SCHEMA_DIR / f"{slug}.md"
        if not page.is_file():
            failures.append(f"missing schema page: {page.relative_to(ROOT)}")
            continue
        text = page.read_text(encoding="utf-8")
        if f"# `{name}` JSON Schema" not in text:
            failures.append(f"{page.relative_to(ROOT)} does not title {name}")
        if GENERATED not in text:
            failures.append(f"{page.relative_to(ROOT)} is missing the generated-page marker")
        match = re.search(r"```json\n(.*?)\n```", text, re.DOTALL)
        if not match:
            failures.append(f"{page.relative_to(ROOT)} has no JSON fenced block")
            continue
        try:
            parsed = json.loads(match.group(1))
        except json.JSONDecodeError as error:
            failures.append(f"{page.relative_to(ROOT)} has invalid JSON: {error}")
            continue
        if not isinstance(parsed, dict):
            failures.append(f"{page.relative_to(ROOT)} does not contain a JSON object")
    for page in sorted(SCHEMA_DIR.glob("*.md")):
        if page.name == "README.md":
            continue
        if page.stem not in {slugify_type(name) for name in expected}:
            failures.append(f"unexpected schema page: {page.relative_to(ROOT)}")
    return failures


def check_index() -> list[str]:
    failures = []
    page = REFERENCE / "README.md"
    if not page.is_file():
        return [f"missing page: {page.relative_to(ROOT)}"]
    text = page.read_text(encoding="utf-8")
    for target in ("cli.md", "schema/README.md"):
        if f"]({target})" not in text:
            failures.append(f"docs/reference/README.md does not link {target}")
    return failures


def main() -> int:
    failures = check_cli() + check_schema() + check_index()
    if failures:
        for failure in failures:
            fail(failure)
        print(f"FAIL  reference: {len(failures)} problem(s)", file=sys.stderr)
        return 1
    commands = top_level_commands()
    schemas = schema_names()
    print(
        f"PASS  reference: cli.md covers {len(commands)} top-level commands "
        f"(V0_1_COMMANDS + V0_2_COMMANDS, hidden interfaces included) "
        f"and {len(schemas)} JSON Schema pages parse"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
