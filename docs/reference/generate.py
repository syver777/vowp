#!/usr/bin/env python3
"""Regenerate the v0.1 + v0.2 CLI and JSON Schema reference pages.

The CLI page is the built binary's complete `--help` tree, committed as text. The schema
pages are the output of `vowp schema <Type>` for every exported wire type. Nothing here
invents commands or fields: both halves come from the binary.

Usage:
    cargo build -p vowp-cli --bin vowp
    python3 docs/reference/generate.py          # write the pages
    python3 docs/reference/generate.py --check  # fail if a committed page is stale
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "docs" / "reference"
SCHEMA_DIR = REFERENCE / "schema"
CLI_RS = ROOT / "crates" / "vowp-cli" / "src" / "cli.rs"
SCHEMA_RS = ROOT / "crates" / "vowp-protocol" / "src" / "schema.rs"

GENERATED = "<!-- generated by docs/reference/generate.py; do not edit -->"

# Hidden nested subcommands do not appear under `Commands:` in `--help`, but they are part
# of the binary and belong in the tree. Keep this list next to the command constants in
# `crates/vowp-cli/src/cli.rs`.
HIDDEN_SUBCOMMANDS: dict[str, tuple[str, ...]] = {
    "session": ("turn-begin", "ingest", "lease", "takeover"),
    "setup": ("__home-init",),
    "orchestrator": ("__keepalive",),
}

CLI_HEADER = f"""# `vowp` CLI reference

Status: current

{GENERATED}

This page is the complete `--help` tree of the `vowp` binary, committed as text. The command
surface is `V0_1_COMMANDS` plus `V0_2_COMMANDS` in
[`crates/vowp-cli/src/cli.rs`](../../crates/vowp-cli/src/cli.rs); the behaviour of each command is
specified in [`docs/design/cli.md`](../design/cli.md). Hidden commands are included because they
are part of the binary even when `vowp --help` does not advertise them.

Regenerate after a CLI change:

```sh
cargo build -p vowp-cli --bin vowp
python3 docs/reference/generate.py
python3 docs/reference/check-reference.py
```

## Command index

| Command | Purpose |
|---|---|
"""

SCHEMA_HEADER = """# JSON Schema reference

Status: current

{generated}

`vowp schema` lists every exported wire type and `vowp schema <Type>` prints its JSON Schema
document. The schemas are generated by `schemars` from the protocol types in
[`docs/design/types.md`](../../design/types.md); these pages reproduce that output verbatim.

Regenerate after a protocol type change:

```sh
cargo build -p vowp-cli --bin vowp
python3 docs/reference/generate.py
python3 docs/reference/check-reference.py
```

| Type | Page |
|---|---|
"""

SUMMARY = """# Reference

Status: current

Generated reference for the v0.1 and v0.2 `vowp` binary. The prose specification lives in
[`docs/design/`](../design/README.md); these pages are the checked-in output of the binary itself.

| Page | Contents |
|---|---|
| [CLI reference](cli.md) | Every command and flag, from the complete `vowp --help` tree |
| [JSON Schema reference](schema/README.md) | One page per wire type, from `vowp schema <Type>` |

## What is generated

- [`cli.md`](cli.md) reproduces the full help tree: the root `vowp --help` page, every
  top-level command, and every nested subcommand. The command set is
  `V0_1_COMMANDS` plus `V0_2_COMMANDS` in
  [`crates/vowp-cli/src/cli.rs`](../../crates/vowp-cli/src/cli.rs), so hidden commands such as
  `vowp __window`, `vowp __exec`, `vowp __vault-exec` and `vowp __vault-admin` are documented even
  though they are absent from the short help listing.
- [`schema/`](schema/README.md) has one page per type returned by `vowp schema`. Each page is
  the verbatim output of `vowp schema <Type>`, generated by `schemars` from the protocol types
  specified in [`docs/design/types.md`](../design/types.md). That includes the v0.2 snapshot,
  capacity, surface/lease, catalog, vault, fleet, tunnel and migration types.

Do not edit the generated pages by hand. Change the CLI or protocol type and regenerate.

## Regenerating

Build the binary first; the generator also sets up a temporary node home so it never touches
the real `~/.vowp`:

```sh
cargo build -p vowp-cli --bin vowp
python3 docs/reference/generate.py
python3 docs/reference/check-reference.py
```

`generate.py` writes the pages and removes stale schema pages. `generate.py --check` compares
the committed pages with fresh binary output without writing anything. Set `VOWP_BIN` to use a
binary outside the workspace target directory.

`check-reference.py` is the offline acceptance check: it proves the CLI page covers exactly the
`V0_1_COMMANDS` and `V0_2_COMMANDS` constants that `help_lists_every_v0_1_command` asserts, and
that every exported schema has a page containing valid JSON.
"""


def run(binary: Path, args: list[str], *, home: Path | None = None, cwd: Path | None = None) -> str:
    """Runs the binary and returns stdout, or raises with stderr on failure."""
    command = [str(binary)]
    if home is not None:
        command.extend(["--home", str(home)])
    command.extend(args)
    env = os.environ.copy()
    env["NO_COLOR"] = "1"
    env["TERM"] = "dumb"
    if home is not None:
        env["HOME"] = str(home)
        env["VOWP_HOME"] = str(home)
    result = subprocess.run(
        command,
        cwd=cwd,
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if result.returncode != 0:
        raise SystemExit(
            f"command failed ({result.returncode}): {' '.join(command)}\n{result.stderr}"
        )
    return result.stdout


def find_binary() -> Path:
    """Finds the built `vowp` binary or explains how to build it."""
    if value := os.environ.get("VOWP_BIN"):
        path = Path(value)
        if path.is_file():
            return path
        raise SystemExit(f"VOWP_BIN does not name a file: {path}")
    target = Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "target"))
    for profile in ("debug", "release"):
        path = target / profile / "vowp"
        if path.is_file():
            return path
    raise SystemExit(
        "no vowp binary found; run `cargo build -p vowp-cli --bin vowp` "
        "or set VOWP_BIN=/path/to/vowp"
    )


def command_const(name: str) -> list[str]:
    """Reads one `V*_COMMANDS` constant, in source order."""
    text = CLI_RS.read_text(encoding="utf-8")
    match = re.search(rf"pub const {name}:.*?=\s*&\[(.*?)\];", text, re.DOTALL)
    if not match:
        raise SystemExit(f"cannot parse {name} from {CLI_RS}")
    return re.findall(r'"([^"]+)"', match.group(1))


def top_level_commands() -> list[str]:
    """Every top-level command, including hidden implementation interfaces."""
    commands = command_const("V0_1_COMMANDS") + command_const("V0_2_COMMANDS")
    # Keep first-seen order so the page follows cli.rs even if a name ever appears twice.
    return list(dict.fromkeys(commands))


def subcommands(help_text: str) -> list[str]:
    """Returns the `Commands:` entries of one help page, in order."""
    lines = help_text.splitlines()
    try:
        start = lines.index("Commands:")
    except ValueError:
        return []
    names = []
    for line in lines[start + 1 :]:
        if not line.strip():
            continue
        if not line.startswith(" "):
            break
        match = re.match(r"^  ([a-z_][a-z0-9_-]*)\s{2,}\S", line)
        if match:
            names.append(match.group(1))
    return names


def slugify_type(name: str) -> str:
    """`BriefFrontMatter` -> `brief-front-matter`."""
    first = re.sub(r"(?<!^)(?=[A-Z])", "-", name)
    return first.lower()


def heading_slug(path: list[str]) -> str:
    text = ("vowp " + " ".join(path)).strip().lower()
    return re.sub(r"[^\w\- ]", "", text).replace(" ", "-")


def summary_line(help_text: str) -> str:
    for line in help_text.splitlines():
        if line.strip():
            return line.strip().replace("|", "\\|")
    return ""


def render_cli(binary: Path, commands: list[str]) -> str:
    """Renders the CLI page from the binary's full help tree."""
    root_help = run(binary, ["--help"])
    sections: list[tuple[list[str], str]] = [([], root_help)]

    def visit(path: list[str]) -> None:
        text = run(binary, [*path, "--help"])
        sections.append((path, text))
        names = subcommands(text)
        if len(path) == 1:
            names.extend(HIDDEN_SUBCOMMANDS.get(path[0], ()))
        for name in dict.fromkeys(names):
            visit([*path, name])

    for command in commands:
        visit([command])

    rows = []
    for path, text in sections:
        if not path:
            label = "`vowp`"
            target = "#vowp"
        else:
            label = "`vowp " + " ".join(path) + "`"
            target = "#" + heading_slug(path)
        rows.append(f"| [{label}]({target}) | {summary_line(text)} |")

    parts = [CLI_HEADER.rstrip("\n"), "\n".join(rows), ""]
    for path, text in sections:
        title = "`vowp`" if not path else "`vowp " + " ".join(path) + "`"
        level = "##" if not path else "#" * (len(path) + 2)
        parts.append(f"{level} {title}\n")
        parts.append("```text")
        parts.append(text.rstrip("\n"))
        parts.append("```\n")
    return "\n".join(parts).rstrip("\n") + "\n"


def schema_names(binary: Path, home: Path) -> list[str]:
    """Asks the binary for the exported schema names."""
    output = run(binary, ["schema"], home=home)
    return [line.strip() for line in output.splitlines() if line.strip()]


def render_schema_page(name: str, schema: str) -> str:
    return (
        f"# `{name}` JSON Schema\n\n"
        "Status: current\n\n"
        f"{GENERATED}\n\n"
        f"Exported by `vowp schema {name}` and generated from the protocol types in\n"
        "[`docs/design/types.md`](../../design/types.md).\n\n"
        "```json\n"
        f"{schema.rstrip()}\n"
        "```\n"
    )


def render_schema_index(names: list[str]) -> str:
    rows = [
        f"| `{name}` | [{slugify_type(name)}.md]({slugify_type(name)}.md) |"
        for name in names
    ]
    return (
        SCHEMA_HEADER.format(generated=GENERATED)
        + "\n".join(rows)
        + "\n"
    )


def rendered_pages(binary: Path, home: Path) -> dict[Path, str]:
    """Renders every generated page without touching the worktree."""
    names = schema_names(binary, home)
    pages = {REFERENCE / "cli.md": render_cli(binary, top_level_commands())}
    pages[SCHEMA_DIR / "README.md"] = render_schema_index(names)
    for name in names:
        schema = run(binary, ["schema", name], home=home)
        pages[SCHEMA_DIR / f"{slugify_type(name)}.md"] = render_schema_page(name, schema)
    return pages


def prepare_home(binary: Path, workdir: Path) -> Path:
    """Creates a throwaway node home and project for commands that need a Ctx."""
    home = workdir / "home"
    project = workdir / "project"
    project.mkdir()
    subprocess.run(["git", "init", "-q"], cwd=project, check=True, env={**os.environ, "HOME": str(home)})
    run(binary, ["init", "--no-framework"], home=home, cwd=project)
    return home


def write_pages(pages: dict[Path, str]) -> None:
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in pages.items():
        path.write_text(content, encoding="utf-8")
    # Drop pages for types that no longer exist.
    for path in SCHEMA_DIR.glob("*.md"):
        if path.name != "README.md" and path not in pages:
            path.unlink()


def check_pages(pages: dict[Path, str]) -> int:
    stale = []
    for path, content in sorted(pages.items()):
        if not path.is_file():
            stale.append(f"missing: {path.relative_to(ROOT)}")
        elif path.read_text(encoding="utf-8") != content:
            stale.append(f"stale:   {path.relative_to(ROOT)}")
    for path in sorted(SCHEMA_DIR.glob("*.md")):
        if path.name != "README.md" and path not in pages:
            stale.append(f"extra:   {path.relative_to(ROOT)}")
    if stale:
        print("reference pages are out of date:", file=sys.stderr)
        for item in stale:
            print(f"  {item}", file=sys.stderr)
        print("run `python3 docs/reference/generate.py`", file=sys.stderr)
        return 1
    print(f"PASS  reference: {len(pages)} generated pages are current")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()

    binary = find_binary()
    with tempfile.TemporaryDirectory(prefix="vowp-reference-") as temporary:
        workdir = Path(temporary)
        home = prepare_home(binary, workdir)
        pages = rendered_pages(binary, home)
    if args.check:
        return check_pages(pages)
    write_pages(pages)
    print(f"wrote {len(pages)} reference pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
