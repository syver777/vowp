//! Service install: one launchd `LaunchAgent` or one systemd user unit.
//!
//! Spec: `docs/design/v0.4/hardening.md` §3. The library renders, validates, installs and
//! uninstalls exactly one unit file per user. It never runs as root, never writes a system-wide
//! unit, never uses `sudo`, never runs the service manager without an explicit `--now`, and
//! never removes a file it did not generate. The CLI wiring is `v4-local-4f-cli-surface`.
//!
//! The unit carries the resolved binary path, the state directory and the installing shell's
//! `PATH`: no token, code, key, provider value or absolute project path. Every generated file is
//! 0600 under a user-owned directory.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

use crate::config::write_private;
use crate::error::AgentError;
use crate::isolation::{self, IsolationError};

/// The launchd label.
pub const LAUNCHD_LABEL: &str = "dev.vowp.agent";
/// The launchd plist file name.
pub const LAUNCHD_PLIST: &str = "dev.vowp.agent.plist";
/// The systemd user unit name.
pub const SYSTEMD_UNIT: &str = "vowp-agent.service";
/// The line every VOWP-generated unit carries; uninstall removes only a file with it.
pub const SERVICE_MARKER: &str = "generated by vowp agent service install";
/// The launchd restart marker under the state directory.
pub const RUN_MARKER: &str = "run";
/// The log directory below the state directory.
pub const LOG_DIR: &str = "logs";
/// The log file below the state directory.
pub const LOG_FILE: &str = "logs/agent.log";
/// PATH used when the installing shell has none.
pub const DEFAULT_PATH: &str = "/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin";

/// Which manager a unit belongs to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ServicePlatform {
    /// macOS launchd `LaunchAgent`.
    Launchd,
    /// Linux `systemd --user`.
    SystemdUser,
}

impl ServicePlatform {
    /// Returns the platform this binary was built for, or `None` on an unsupported target.
    pub fn current() -> Option<Self> {
        #[cfg(target_os = "macos")]
        {
            Some(Self::Launchd)
        }
        #[cfg(target_os = "linux")]
        {
            Some(Self::SystemdUser)
        }
        #[cfg(not(any(target_os = "macos", target_os = "linux")))]
        {
            None
        }
    }

    /// Returns the stable name used in messages.
    pub fn name(self) -> &'static str {
        match self {
            Self::Launchd => "launchd",
            Self::SystemdUser => "systemd-user",
        }
    }

    /// Returns the unit or label name.
    pub fn unit_name(self) -> &'static str {
        match self {
            Self::Launchd => LAUNCHD_LABEL,
            Self::SystemdUser => SYSTEMD_UNIT,
        }
    }
}

/// A refusal from the service install or uninstall path.
#[derive(Debug, thiserror::Error)]
pub enum ServiceError {
    /// This target has no supported service manager.
    #[error("agent service is supported on Linux and macOS only")]
    UnsupportedPlatform,
    /// `HOME` is not set.
    #[error("HOME is not set; the service unit needs the installing user's home")]
    MissingHome,
    /// A path or option is invalid.
    #[error("config: {0}")]
    Config(String),
    /// The unit path holds a file VOWP did not generate.
    #[error("{} holds a file VOWP did not generate; pass --force to replace it", .path.display())]
    ForeignUnit {
        /// Offending unit path.
        path: PathBuf,
    },
    /// The manager command could not be found.
    #[error("the service manager command is not available: {command}")]
    ManagerMissing {
        /// The command that was not found.
        command: String,
    },
    /// The manager command failed.
    #[error("{command} failed with {status:?}: {stderr}")]
    ManagerFailed {
        /// The command that failed.
        command: String,
        /// Exit status, when the process ran.
        status: Option<i32>,
        /// Captured standard error.
        stderr: String,
    },
    /// The state directory or unit parent is not safe.
    #[error("isolation: {0}")]
    Isolation(#[from] IsolationError),
    /// A filesystem operation failed.
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
}

impl ServiceError {
    /// Returns the documented CLI exit code.
    pub fn exit_code(&self) -> i32 {
        match self {
            Self::MissingHome | Self::Config(_) => 2,
            Self::ForeignUnit { .. } => 4,
            Self::UnsupportedPlatform => 5,
            Self::Isolation(error) => error.exit_code(),
            Self::ManagerMissing { .. } | Self::ManagerFailed { .. } => 7,
            Self::Io(_) => 1,
        }
    }
}

/// One user's service specification.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServiceSpec {
    /// Manager family.
    pub platform: ServicePlatform,
    /// Absolute path to the `vowp` binary.
    pub binary: PathBuf,
    /// Absolute agent state directory (`~/.vowp-agent`).
    pub state_dir: PathBuf,
    /// The installing user's home.
    pub home: PathBuf,
    /// `$XDG_CONFIG_HOME` when it is absolute.
    pub xdg_config_home: Option<PathBuf>,
    /// The installing shell's `PATH`.
    pub path_env: String,
    /// The installing user's uid.
    pub uid: u32,
}

impl ServiceSpec {
    /// Builds a spec from explicit values (tests and embedding).
    pub fn new(
        platform: ServicePlatform,
        binary: impl Into<PathBuf>,
        state_dir: impl Into<PathBuf>,
        home: impl Into<PathBuf>,
        path_env: impl Into<String>,
        uid: u32,
    ) -> Self {
        Self {
            platform,
            binary: binary.into(),
            state_dir: state_dir.into(),
            home: home.into(),
            xdg_config_home: None,
            path_env: path_env.into(),
            uid,
        }
    }

    /// Builds the current user's spec from `HOME`, `XDG_CONFIG_HOME`, `PATH` and `id -u`.
    pub fn for_current_user(binary: PathBuf, state_dir: PathBuf) -> Result<Self, ServiceError> {
        let platform = ServicePlatform::current().ok_or(ServiceError::UnsupportedPlatform)?;
        let home = std::env::var_os("HOME")
            .map(PathBuf::from)
            .ok_or(ServiceError::MissingHome)?;
        let xdg_config_home = std::env::var_os("XDG_CONFIG_HOME")
            .map(PathBuf::from)
            .filter(|path| path.is_absolute());
        let path_env = std::env::var("PATH").unwrap_or_else(|_| DEFAULT_PATH.to_owned());
        let uid = isolation::current_uid()?;
        Ok(Self {
            platform,
            binary,
            state_dir,
            home,
            xdg_config_home,
            path_env,
            uid,
        })
    }

    /// Returns the unit path for this platform.
    pub fn unit_path(&self) -> Result<PathBuf, ServiceError> {
        if !self.home.is_absolute() {
            return Err(ServiceError::Config(
                "the installing user's HOME must be absolute".to_owned(),
            ));
        }
        match self.platform {
            ServicePlatform::Launchd => Ok(self.home.join("Library/LaunchAgents").join(LAUNCHD_PLIST)),
            ServicePlatform::SystemdUser => {
                let root = match &self.xdg_config_home {
                    Some(path) if path.is_absolute() => path.clone(),
                    _ => self.home.join(".config"),
                };
                Ok(root.join("systemd/user").join(SYSTEMD_UNIT))
            }
        }
    }

    /// Validates the pure path and user rules without creating or writing anything.
    pub fn validate(&self) -> Result<(), ServiceError> {
        isolation::ensure_not_root(self.uid)?;
        if !self.binary.is_absolute() {
            return Err(ServiceError::Config("the vowp binary path must be absolute".to_owned()));
        }
        if !self.state_dir.is_absolute() {
            return Err(ServiceError::Config(
                "the agent state directory must be absolute".to_owned(),
            ));
        }
        self.unit_path()?;
        Ok(())
    }

    /// Creates and checks the state, log and unit-parent directories.
    pub fn prepare(&self) -> Result<(), ServiceError> {
        self.validate()?;
        isolation::ensure_state_dir(&self.state_dir, self.uid)?;
        isolation::ensure_log_dir(&self.state_dir, self.uid)?;
        let unit_path = self.unit_path()?;
        if let Some(parent) = unit_path.parent() {
            isolation::check_unit_parent(parent, self.uid)?;
        }
        Ok(())
    }

    /// Renders the unit text for this platform.
    pub fn render(&self) -> Result<String, ServiceError> {
        self.validate()?;
        match self.platform {
            ServicePlatform::Launchd => Ok(self.render_launchd()),
            ServicePlatform::SystemdUser => Ok(self.render_systemd()),
        }
    }

    /// Renders the launchd plist from §3.2.
    pub fn render_launchd(&self) -> String {
        let binary = xml_escape(&self.binary.display().to_string());
        let state = xml_escape(&self.state_dir.display().to_string());
        let path = xml_escape(&self.path_env);
        let log = xml_escape(&self.state_dir.join(LOG_FILE).display().to_string());
        format!(
            r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- {SERVICE_MARKER} -->
<plist version="1.0">
<dict>
  <key>Label</key><string>{LAUNCHD_LABEL}</string>
  <key>ProgramArguments</key>
  <array>
    <string>{binary}</string>
    <string>agent</string><string>run</string>
    <string>--foreground</string><string>--service</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>VOWP_AGENT_HOME</key><string>{state}</string>
    <key>PATH</key><string>{path}</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key>
  <dict>
    <key>PathState</key>
    <dict><key>{state}/run</key><true/></dict>
  </dict>
  <key>ThrottleInterval</key><integer>10</integer>
  <key>ExitTimeOut</key><integer>20</integer>
  <key>Umask</key><integer>63</integer>
  <key>StandardOutPath</key><string>{log}</string>
  <key>StandardErrorPath</key><string>{log}</string>
</dict>
</plist>
"#
        )
    }

    /// Renders the systemd user unit from §3.3.
    pub fn render_systemd(&self) -> String {
        let binary = systemd_quote(&self.binary.display().to_string());
        let state = systemd_quote(&self.state_dir.display().to_string());
        let path = systemd_quote(&self.path_env);
        format!(
            r#"# {SERVICE_MARKER}
[Unit]
Description=VOWP local agent
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart={binary} agent run --foreground --service
Environment=VOWP_AGENT_HOME={state}
Environment=PATH={path}
Restart=on-failure
RestartPreventExitStatus=4 5
RestartSec=5
KillMode=mixed
TimeoutStopSec=20
Umask=0077

[Install]
WantedBy=default.target
"#
        )
    }

    /// Returns the manager commands `install` prints and, with `--now`, runs.
    pub fn install_commands(&self) -> Result<Vec<Vec<String>>, ServiceError> {
        let unit = self.unit_path()?;
        Ok(match self.platform {
            ServicePlatform::Launchd => vec![
                vec![
                    "launchctl".to_owned(),
                    "bootstrap".to_owned(),
                    format!("gui/{}", self.uid),
                    unit.display().to_string(),
                ],
                vec![
                    "launchctl".to_owned(),
                    "enable".to_owned(),
                    format!("gui/{}/{}", self.uid, LAUNCHD_LABEL),
                ],
            ],
            ServicePlatform::SystemdUser => vec![vec![
                "systemctl".to_owned(),
                "--user".to_owned(),
                "daemon-reload".to_owned(),
            ]],
        })
    }

    /// Returns the commands that start the job now; only `--now` runs them.
    pub fn start_commands(&self) -> Vec<Vec<String>> {
        match self.platform {
            ServicePlatform::Launchd => vec![vec![
                "launchctl".to_owned(),
                "kickstart".to_owned(),
                "-k".to_owned(),
                format!("gui/{}/{}", self.uid, LAUNCHD_LABEL),
            ]],
            ServicePlatform::SystemdUser => vec![vec![
                "systemctl".to_owned(),
                "--user".to_owned(),
                "enable".to_owned(),
                "--now".to_owned(),
                SYSTEMD_UNIT.to_owned(),
            ]],
        }
    }

    /// Returns the commands that stop and remove the unit.
    pub fn uninstall_commands(&self) -> Vec<Vec<String>> {
        match self.platform {
            ServicePlatform::Launchd => vec![vec![
                "launchctl".to_owned(),
                "bootout".to_owned(),
                format!("gui/{}/{}", self.uid, LAUNCHD_LABEL),
            ]],
            ServicePlatform::SystemdUser => vec![
                vec![
                    "systemctl".to_owned(),
                    "--user".to_owned(),
                    "disable".to_owned(),
                    "--now".to_owned(),
                    SYSTEMD_UNIT.to_owned(),
                ],
                vec!["systemctl".to_owned(), "--user".to_owned(), "daemon-reload".to_owned()],
            ],
        }
    }

    /// Returns the command that reads the manager's status.
    pub fn status_command(&self) -> Vec<String> {
        match self.platform {
            ServicePlatform::Launchd => vec![
                "launchctl".to_owned(),
                "print".to_owned(),
                format!("gui/{}/{}", self.uid, LAUNCHD_LABEL),
            ],
            ServicePlatform::SystemdUser => vec![
                "systemctl".to_owned(),
                "--user".to_owned(),
                "show".to_owned(),
                SYSTEMD_UNIT.to_owned(),
                "--property=LoadState,ActiveState,MainPID,ExecMainStatus".to_owned(),
                "--no-pager".to_owned(),
            ],
        }
    }

    /// Returns the linger hint for a systemd user unit: printed, never run with `sudo`.
    pub fn linger_hint(&self) -> Option<String> {
        match self.platform {
            ServicePlatform::Launchd => None,
            ServicePlatform::SystemdUser => Some(format!(
                "loginctl enable-linger {} (run it yourself; VOWP never uses sudo)",
                owner_name().unwrap_or_else(|| "<user>".to_owned())
            )),
        }
    }
}

fn owner_name() -> Option<String> {
    std::env::var("USER").ok().or_else(|| std::env::var("LOGNAME").ok())
}

/// One manager invocation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CommandRecord {
    /// The argv that ran.
    pub argv: Vec<String>,
    /// Exit status, when the process ran.
    pub status: Option<i32>,
    /// Captured standard output.
    pub stdout: String,
    /// Captured standard error.
    pub stderr: String,
}

impl CommandRecord {
    /// Returns whether the command exited successfully.
    pub fn success(&self) -> bool {
        self.status == Some(0)
    }
}

/// The service manager boundary; tests inject a fake.
pub trait ServiceManager: Send + Sync {
    /// Runs one manager command.
    fn run(&self, argv: &[String]) -> Result<CommandRecord, ServiceError>;

    /// Returns whether the manager binary is available.
    fn available(&self) -> bool;
}

/// The real service manager: runs the argv on `PATH` as the current user.
#[derive(Debug, Clone, Copy, Default)]
pub struct SystemManager;

impl ServiceManager for SystemManager {
    fn run(&self, argv: &[String]) -> Result<CommandRecord, ServiceError> {
        let (program, args) = argv
            .split_first()
            .ok_or_else(|| ServiceError::Config("the service manager command is empty".to_owned()))?;
        let output = match std::process::Command::new(program).args(args).output() {
            Ok(output) => output,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                return Err(ServiceError::ManagerMissing {
                    command: program.clone(),
                });
            }
            Err(error) => return Err(ServiceError::Io(error)),
        };
        Ok(CommandRecord {
            argv: argv.to_vec(),
            status: output.status.code(),
            stdout: String::from_utf8_lossy(&output.stdout).into_owned(),
            stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
        })
    }

    fn available(&self) -> bool {
        let program = match ServicePlatform::current() {
            Some(ServicePlatform::Launchd) => "launchctl",
            Some(ServicePlatform::SystemdUser) => "systemctl",
            None => return false,
        };
        std::process::Command::new(program)
            .arg("--version")
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .is_ok()
    }
}

/// How `install` is invoked.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct InstallOptions {
    /// Write nothing and invoke no manager; print the unit and the commands.
    pub print_only: bool,
    /// Replace a file at the unit path that VOWP did not generate.
    pub force: bool,
    /// Run the manager commands now.
    pub now: bool,
}

/// The result of one `install`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InstallReport {
    /// Unit path the installer used or would use.
    pub unit_path: PathBuf,
    /// Unit text.
    pub text: String,
    /// Manager commands to print; with `--now` they have already run.
    pub commands: Vec<Vec<String>>,
    /// Whether the unit file was written.
    pub installed: bool,
    /// The launchd restart marker, when this platform uses one.
    pub run_marker: Option<PathBuf>,
    /// The linger hint for systemd user units.
    pub linger_hint: Option<String>,
}

/// Renders, validates and (unless `--print`) writes exactly one unit file.
///
/// The manager runs only with `--now`. A launchd install writes the `run` marker before it
/// bootstraps the job, so a crash before the first connection still restarts.
pub fn install(
    spec: &ServiceSpec,
    options: &InstallOptions,
    manager: &dyn ServiceManager,
) -> Result<InstallReport, ServiceError> {
    spec.validate()?;
    let unit_path = spec.unit_path()?;
    let text = spec.render()?;
    let mut commands = spec.install_commands()?;
    commands.extend(spec.start_commands());
    let linger_hint = spec.linger_hint();
    if options.print_only {
        return Ok(InstallReport {
            unit_path,
            text,
            commands,
            installed: false,
            run_marker: None,
            linger_hint,
        });
    }
    spec.prepare()?;
    if unit_path.exists() {
        let existing = fs::read_to_string(&unit_path).unwrap_or_default();
        if !existing.contains(SERVICE_MARKER) && !options.force {
            return Err(ServiceError::ForeignUnit { path: unit_path });
        }
    }
    write_unit(&unit_path, &text)?;
    isolation::check_private_file(&unit_path, spec.uid)?;
    let run_marker = if spec.platform == ServicePlatform::Launchd {
        Some(write_run_marker(&spec.state_dir, spec.uid)?)
    } else {
        None
    };
    if options.now {
        for command in &commands {
            let record = manager.run(command)?;
            if !record.success() {
                return Err(ServiceError::ManagerFailed {
                    command: record.argv.join(" "),
                    status: record.status,
                    stderr: record.stderr,
                });
            }
        }
    }
    Ok(InstallReport {
        unit_path,
        text,
        commands,
        installed: true,
        run_marker,
        linger_hint,
    })
}

/// The result of one `uninstall`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UninstallReport {
    /// Unit path the uninstaller looked at.
    pub unit_path: PathBuf,
    /// Whether a VOWP-generated file was removed.
    pub removed: bool,
    /// Manager commands that were run.
    pub commands: Vec<Vec<String>>,
}

/// Stops the unit first, then removes only a file carrying the VOWP marker.
///
/// The state directory, the node key and every surface token stay in place.
pub fn uninstall(spec: &ServiceSpec, manager: &dyn ServiceManager) -> Result<UninstallReport, ServiceError> {
    spec.validate()?;
    let unit_path = spec.unit_path()?;
    let commands = spec.uninstall_commands();
    if !unit_path.exists() {
        return Ok(UninstallReport {
            unit_path,
            removed: false,
            commands: Vec::new(),
        });
    }
    let existing = fs::read_to_string(&unit_path).unwrap_or_default();
    if !existing.contains(SERVICE_MARKER) {
        return Err(ServiceError::ForeignUnit { path: unit_path });
    }
    for command in &commands {
        let record = manager.run(command)?;
        if !record.success() && record.status != Some(0) {
            return Err(ServiceError::ManagerFailed {
                command: record.argv.join(" "),
                status: record.status,
                stderr: record.stderr,
            });
        }
    }
    fs::remove_file(&unit_path)?;
    Ok(UninstallReport {
        unit_path,
        removed: true,
        commands,
    })
}

/// The manager's view of one installed unit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServiceStatus {
    /// Manager family.
    pub platform: ServicePlatform,
    /// Unit path.
    pub unit_path: PathBuf,
    /// Whether the manager binary is available.
    pub available: bool,
    /// Whether the job is loaded, when the manager answered.
    pub loaded: Option<bool>,
    /// The manager's reported pid.
    pub pid: Option<u32>,
    /// The manager's reported last exit status.
    pub last_exit: Option<i32>,
}

/// Reads the manager status. A missing manager is `available = false`, not an error.
pub fn status(spec: &ServiceSpec, manager: &dyn ServiceManager) -> Result<ServiceStatus, ServiceError> {
    spec.validate()?;
    let unit_path = spec.unit_path()?;
    let available = manager.available();
    let mut status = ServiceStatus {
        platform: spec.platform,
        unit_path,
        available,
        loaded: None,
        pid: None,
        last_exit: None,
    };
    if !available {
        return Ok(status);
    }
    let command = spec.status_command();
    let record = match manager.run(&command) {
        Ok(record) => record,
        Err(ServiceError::ManagerMissing { .. }) => {
            status.available = false;
            return Ok(status);
        }
        Err(error) => return Err(error),
    };
    if !record.success() {
        status.loaded = Some(false);
        return Ok(status);
    }
    match spec.platform {
        ServicePlatform::Launchd => parse_launchctl(&record.stdout, &mut status),
        ServicePlatform::SystemdUser => parse_systemctl(&record.stdout, &mut status),
    }
    Ok(status)
}

fn parse_launchctl(stdout: &str, status: &mut ServiceStatus) {
    let mut loaded = false;
    for line in stdout.lines() {
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let key = key.trim();
        let value = value.trim();
        match key {
            "state" => loaded = matches!(value, "running" | "waiting" | "on demand"),
            "pid" => status.pid = value.parse().ok(),
            "last exit status" => status.last_exit = value.parse().ok(),
            _ => {}
        }
    }
    status.loaded = Some(loaded || status.pid.is_some());
}

fn parse_systemctl(stdout: &str, status: &mut ServiceStatus) {
    for line in stdout.lines() {
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        match key {
            "LoadState" => status.loaded = Some(value == "loaded"),
            "ActiveState" => {
                if value == "active" {
                    status.loaded = Some(true);
                }
            }
            "MainPID" => status.pid = value.parse().ok().filter(|pid| *pid != 0),
            "ExecMainStatus" => status.last_exit = value.parse().ok(),
            _ => {}
        }
    }
}

/// Returns `state_dir/run`.
pub fn run_marker_path(state_dir: &Path) -> PathBuf {
    state_dir.join(RUN_MARKER)
}

/// Writes the launchd restart marker 0600 in the checked state directory.
pub fn write_run_marker(state_dir: &Path, uid: u32) -> Result<PathBuf, ServiceError> {
    isolation::ensure_state_dir(state_dir, uid)?;
    let path = run_marker_path(state_dir);
    write_private(&path, b"").map_err(|error| ServiceError::Io(std::io::Error::other(error)))?;
    isolation::check_private_file(&path, uid)?;
    Ok(path)
}

/// Removes the restart marker. Returns whether it existed.
pub fn remove_run_marker(state_dir: &Path) -> Result<bool, ServiceError> {
    match fs::remove_file(run_marker_path(state_dir)) {
        Ok(()) => Ok(true),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(ServiceError::Io(error)),
    }
}

/// The terminal outcome of an `agent run --service`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ServiceRunOutcome {
    /// The home revoked the node or another connection took over; the launchd marker is gone.
    Terminal(crate::client::RunOutcome),
    /// The stop flag asked for a drain; the marker stays for the next start.
    Drained,
}

/// Checks the run environment without writing the launchd marker.
///
/// `agent run` uses this for every mode: the state directory must be a real 0700 directory
/// owned by the current uid, and the process must not be root.
pub fn check_run_environment(state_dir: &Path) -> Result<(), AgentError> {
    let uid = isolation::current_uid().map_err(|error| AgentError::Config(error.to_string()))?;
    isolation::ensure_not_root(uid).map_err(|error| AgentError::Config(error.to_string()))?;
    isolation::ensure_state_dir(state_dir, uid).map_err(|error| AgentError::Config(error.to_string()))?;
    Ok(())
}

/// Prepares `agent run --service`: checks the run environment and writes the launchd marker.
///
/// This is the library seam `vowp agent run --foreground --service` uses. It returns the marker
/// path; the run removes it after a terminal `Revoked` or `Superseded` and keeps it after a
/// drain.
pub fn prepare_service_run(state_dir: &Path) -> Result<PathBuf, AgentError> {
    check_run_environment(state_dir)?;
    let uid = isolation::current_uid().map_err(|error| AgentError::Config(error.to_string()))?;
    write_run_marker(state_dir, uid).map_err(|error| AgentError::Config(error.to_string()))
}

fn write_unit(path: &Path, text: &str) -> Result<(), ServiceError> {
    let parent = path
        .parent()
        .ok_or_else(|| ServiceError::Config(format!("{} has no parent directory", path.display())))?;
    fs::create_dir_all(parent)?;
    let temp = path.with_extension(format!("tmp-{}", std::process::id()));
    fs::write(&temp, text)?;
    fs::set_permissions(&temp, fs::Permissions::from_mode(0o600))?;
    fs::rename(&temp, path)?;
    fs::set_permissions(path, fs::Permissions::from_mode(0o600))?;
    Ok(())
}

fn xml_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

/// Quotes a systemd argument only when it contains a character the parser would split.
fn systemd_quote(value: &str) -> String {
    let safe = !value.is_empty()
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'/' | b'.' | b'_' | b'-' | b':' | b'@' | b'+'));
    if safe {
        return value.to_owned();
    }
    let mut quoted = String::from("\"");
    for character in value.chars() {
        match character {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            '\n' => quoted.push_str("\\n"),
            _ => quoted.push(character),
        }
    }
    quoted.push('"');
    quoted
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec(platform: ServicePlatform) -> ServiceSpec {
        ServiceSpec::new(
            platform,
            "/usr/local/bin/vowp",
            "/tmp/agent-state",
            "/tmp/agent-home",
            DEFAULT_PATH,
            501,
        )
    }

    #[test]
    fn launchd_plist_has_the_documented_shape_and_no_secret() {
        let text = spec(ServicePlatform::Launchd).render_launchd();
        assert!(text.contains("<!-- generated by vowp agent service install -->"));
        assert!(text.contains("<string>dev.vowp.agent</string>"));
        assert!(text.contains("<string>/usr/local/bin/vowp</string>"));
        assert!(text.contains("<string>--foreground</string><string>--service</string>"));
        assert!(text.contains("<key>VOWP_AGENT_HOME</key><string>/tmp/agent-state</string>"));
        assert!(text.contains("<key>/tmp/agent-state/run</key><true/>"));
        assert!(text.contains("<key>Umask</key><integer>63</integer>"));
        for secret in ["token", "code", "node.key", "password"] {
            assert!(!text.contains(secret), "the unit carries no {secret}: {text}");
        }
    }

    #[test]
    fn systemd_unit_has_the_documented_shape_and_no_secret() {
        let text = spec(ServicePlatform::SystemdUser).render_systemd();
        assert!(text.starts_with("# generated by vowp agent service install"));
        assert!(text.contains("ExecStart=/usr/local/bin/vowp agent run --foreground --service"));
        assert!(text.contains("Environment=VOWP_AGENT_HOME=/tmp/agent-state"));
        assert!(text.contains("RestartPreventExitStatus=4 5"));
        assert!(text.contains("Umask=0077"));
        assert!(text.contains("WantedBy=default.target"));
        assert!(!text.contains("User="), "a user unit never names User=");
        for secret in ["token", "code", "node.key", "password"] {
            assert!(!text.contains(secret), "the unit carries no {secret}: {text}");
        }
    }

    #[test]
    fn systemd_quoting_handles_spaces_and_quotes() {
        assert_eq!(systemd_quote("/usr/bin/vowp"), "/usr/bin/vowp");
        assert_eq!(systemd_quote("/opt/my bin/vowp"), "\"/opt/my bin/vowp\"");
        assert_eq!(systemd_quote("a\"b"), "\"a\\\"b\"");
    }

    #[test]
    fn unit_paths_follow_home_and_xdg() {
        let mut spec = spec(ServicePlatform::Launchd);
        assert_eq!(
            spec.unit_path().expect("launchd path"),
            PathBuf::from("/tmp/agent-home/Library/LaunchAgents/dev.vowp.agent.plist")
        );
        spec.platform = ServicePlatform::SystemdUser;
        assert_eq!(
            spec.unit_path().expect("systemd path"),
            PathBuf::from("/tmp/agent-home/.config/systemd/user/vowp-agent.service")
        );
        spec.xdg_config_home = Some(PathBuf::from("/tmp/xdg"));
        assert_eq!(
            spec.unit_path().expect("systemd XDG path"),
            PathBuf::from("/tmp/xdg/systemd/user/vowp-agent.service")
        );
        spec.xdg_config_home = Some(PathBuf::from("relative/xdg"));
        assert_eq!(
            spec.unit_path().expect("relative XDG is ignored"),
            PathBuf::from("/tmp/agent-home/.config/systemd/user/vowp-agent.service")
        );
    }

    #[test]
    fn a_root_spec_is_refused() {
        let mut spec = spec(ServicePlatform::SystemdUser);
        spec.uid = 0;
        assert!(matches!(
            spec.validate(),
            Err(ServiceError::Isolation(IsolationError::Root))
        ));
        assert_eq!(ServiceError::Isolation(IsolationError::Root).exit_code(), 5);
    }

    #[test]
    fn a_foreign_unit_file_is_refused_without_force() {
        let dir = tempfile::tempdir().expect("temp dir");
        let home = dir.path().join("home");
        let state = home.join(".vowp-agent");
        fs::create_dir_all(state.join("logs")).expect("state");
        fs::set_permissions(&state, fs::Permissions::from_mode(0o700)).expect("mode");
        let spec = ServiceSpec::new(
            ServicePlatform::SystemdUser,
            "/usr/local/bin/vowp",
            &state,
            &home,
            DEFAULT_PATH,
            isolation::current_uid().expect("uid"),
        );
        let unit = spec.unit_path().expect("unit path");
        fs::create_dir_all(unit.parent().expect("parent")).expect("parent");
        fs::write(&unit, "[Unit]\nDescription=someone else\n").expect("foreign unit");
        let manager = NoManager;
        let error = install(&spec, &InstallOptions::default(), &manager).expect_err("foreign file");
        assert!(matches!(error, ServiceError::ForeignUnit { .. }));
        assert_eq!(error.exit_code(), 4);
        assert!(unit.exists(), "the foreign file is not replaced");
    }

    struct NoManager;

    impl ServiceManager for NoManager {
        fn run(&self, _argv: &[String]) -> Result<CommandRecord, ServiceError> {
            panic!("the manager must not run");
        }

        fn available(&self) -> bool {
            false
        }
    }
}
