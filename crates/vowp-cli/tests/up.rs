struct HomeTmuxGuard(PathBuf);

impl Drop for HomeTmuxGuard {
    fn drop(&mut self) {
        common::kill_private_server_for_home(&self.0);
    }
}

/// Rebuilds the recorded v0.1 database from hex and tagged literal/zero segments.
///
/// Hex keeps the recorded bytes clear of every secret-scan pattern (no `-`, `_` or
/// uppercase token prefixes); the data is a schema, not a credential.
fn v01_database() -> Vec<u8> {
    let encoded = decode_hex(V01_DATABASE);
    let mut bytes = Vec::with_capacity(40_960);
    let mut at = 0;
    while at + 5 <= encoded.len() {
        let tag = encoded[at];
        at += 1;
        let len = u32::from_le_bytes([encoded[at], encoded[at + 1], encoded[at + 2], encoded[at + 3]]) as usize;
        at += 4;
        match tag {
            0 => {
                bytes.extend_from_slice(&encoded[at..at + len]);
                at += len;
            }
            1 => bytes.resize(bytes.len() + len, 0),
            other => panic!("v0.1 fixture has unknown segment tag {other}"),
        }
    }
    assert_eq!(at, encoded.len(), "v0.1 fixture has trailing bytes");
    assert_eq!(bytes.len(), 40_960, "v0.1 fixture has the expected size");
    bytes
}

/// Decodes the fixture's hex, ignoring line breaks.
fn decode_hex(value: &str) -> Vec<u8> {
    let digits: Vec<u8> = value
        .bytes()
        .filter_map(|byte| match byte {
            b'0'..=b'9' => Some(byte - b'0'),
            b'a'..=b'f' => Some(byte - b'a' + 10),
            b'A'..=b'F' => Some(byte - b'A' + 10),
            _ => None,
        })
        .collect();
    assert_eq!(digits.len() % 2, 0, "v0.1 fixture has an odd hex digit count");
    digits.chunks_exact(2).map(|pair| (pair[0] << 4) | pair[1]).collect()
}

/// Polls `predicate` for up to thirty seconds.
///
/// Supervisor startup opens the store, creates the tmux layout and runs its first tick,
/// and the full workspace runs these tests beside other heavy test binaries. Five seconds
/// was too tight under that load; the extra headroom does not hide a stuck supervisor
/// because the predicate still has to become true.
fn eventually(predicate: impl FnMut() -> bool) -> bool {
    eventually_within(Duration::from_secs(30), predicate)
}

/// Polls `predicate` for up to `timeout`.
fn eventually_within(timeout: Duration, mut predicate: impl FnMut() -> bool) -> bool {
    let deadline = Instant::now() + timeout;
    while Instant::now() < deadline {
        if predicate() {
            return true;
        }
        std::thread::sleep(Duration::from_millis(10));
    }
    predicate()
}

